<p>Be cautious of:</p>



<ul class="wp-block-list">
<li>Too-good-to-be-true prices<br></li>



<li>Sites not requiring prescriptions<br></li>



<li>Poor website design or spelling errors<br></li>



<li>Absence of customer support</li>
