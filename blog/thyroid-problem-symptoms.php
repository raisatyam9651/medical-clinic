<h3 class="wp-block-heading">Thyroid Blood Tests</h3>



<p>Blood tests are at the heart of thyroid diagnosis and are also used to monitor ongoing treatment. The most important first test is <strong>TSH</strong> (Thyroid-Stimulating Hormone). This hormone comes from the pituitary gland and tells the thyroid how hard to work. When the thyroid is underactive, TSH levels usually go up as the pituitary pushes it to work harder. When the thyroid is overactive, TSH levels usually fall because the pituitary is trying to slow the gland down.</p>



