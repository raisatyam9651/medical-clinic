<p>Have you noticed your weight changing since starting a new medicine? You are not alone. <strong>Many common medicines cause weight gain or weight loss</strong> as a side effect. This can be frustrating, especially when you are already managing a health condition and also dealing with unexpected body weight changes.</p>



<h2 class="wp-block-heading">Medicines That Commonly Cause Weight Gain in India</h2>



<h3 class="wp-block-heading">Corticosteroids (Prednisolone, Dexamethasone)</h3>



<p>Corticosteroids are among the most significant causes of medicine-related weight gain. They cause weight gain through multiple mechanisms: increased appetite, fluid retention, redistribution of fat (causing a “moon face” and central abdominal fat accumulation), and direct metabolic effects that promote fat storage. Longer courses and higher doses cause more significant weight gain.</p>



<h3 class="wp-block-heading">Antidepressants</h3>



<p>Many antidepressants cause weight gain over time. Mirtazapine (often prescribed for depression with insomnia) is particularly associated with significant weight gain. Tricyclic antidepressants (amitriptyline, nortriptyline) also commonly cause weight gain. Some SSRIs like paroxetine cause more weight gain than others. Sertraline and escitalopram are generally weight-neutral. Read more about <a href="https://www.bharatmedicalhall.com/blog/why-should-you-never-stop-medicines-suddenly/">managing antidepressant side effects</a>.</p>



<h3 class="wp-block-heading">Antipsychotics</h3>



<p>Antipsychotic medicines, particularly olanzapine, clozapine, and quetiapine, are associated with significant weight gain and metabolic syndrome. They increase appetite, reduce metabolic rate, and alter fat storage. This can sometimes lead to the development of type 2 diabetes. Haloperidol and aripiprazole are less likely to cause weight gain.</p>



<h3 class="wp-block-heading">Diabetes Medicines</h3>



<p>Insulin and sulfonylureas (glipizide, glibenclamide) cause weight gain because they increase insulin levels, which promotes fat storage. This is a common challenge in diabetes management. Metformin, on the other hand, is weight-neutral or may cause slight weight loss. Newer diabetes medicines like SGLT2 inhibitors (dapagliflozin, empagliflozin) and GLP-1 agonists (liraglutide) actually cause weight loss, which is why they are increasingly preferred.</p>



<h3 class="wp-block-heading">Antihistamines</h3>



<p>First-generation antihistamines (chlorpheniramine, cyproheptadine) can cause weight gain by stimulating appetite (cyproheptadine is actually used as an appetite stimulant in some cases) and promoting sleep (which reduces energy expenditure). Learn about <a href="https://www.bharatmedicalhall.com/blog/why-do-medicines-cause-drowsiness/">why medicines cause drowsiness</a>.</p>



<h3 class="wp-block-heading">Beta-Blockers</h3>



<p>Beta-blockers (atenolol, metoprolol, propranolol) are associated with modest weight gain. They reduce heart rate and may reduce physical activity tolerance, contributing to reduced calorie burning. They also slow metabolism slightly.</p>



<h2 class="wp-block-heading">Medicines That Commonly Cause Weight Loss</h2>



<h3 class="wp-block-heading">Metformin</h3>



<p>Metformin is generally weight-neutral but some patients experience modest weight loss due to reduced appetite and GI effects. It remains the first-line diabetes medicine partly because of its weight advantage over sulfonylureas and insulin.</p>



<h3 class="wp-block-heading">Topiramate (Anti-Epileptic)</h3>



<p>Topiramate is associated with significant weight loss as a side effect. It reduces appetite and increases caloric expenditure. It is sometimes used off-label for weight management, though this requires medical supervision.</p>



<h3 class="wp-block-heading">ADHD Medicines (Methylphenidate, Amphetamines)</h3>



<p>Stimulants used for ADHD suppress appetite and increase metabolism, leading to weight loss, particularly in children. This requires careful monitoring in growing children.</p>



<h3 class="wp-block-heading">Some Chemotherapy Medicines</h3>



<p>Many chemotherapy medicines cause nausea, vomiting, and loss of appetite leading to significant unintended weight loss. This is one of the most challenging aspects of cancer treatment management.</p>



<h2 class="wp-block-heading">What to Do If Your Medicine Is Causing Weight Changes</h2>



<ul class="wp-block-list"><li>Discuss with your doctor – do not stop medicine without advice</li><li>Ask if an alternative medicine with less weight effect is available</li><li>Increase physical activity to counteract weight gain if medically appropriate</li><li>Focus on diet – avoid high-calorie, high-sugar foods especially with corticosteroids</li><li>Monitor weight regularly and report significant changes to your doctor</li></ul>



