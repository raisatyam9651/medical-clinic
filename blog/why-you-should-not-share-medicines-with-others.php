<p>Your family member has a headache similar to what you had last week. You offer them the same antibiotic your doctor prescribed for you. Or a friend has a similar complaint and you share your prescription pain medicine. While this seems helpful, <strong>sharing medicines is actually dangerous and can cause serious harm.</strong> Here is why you should never share medicines with others.</p>



<h2 class="wp-block-heading">Why Sharing Medicines Is Dangerous</h2>



<h3 class="wp-block-heading">1. Same Symptoms Don’t Mean Same Diagnosis</h3>



<p>Two people can have similar symptoms from completely different conditions. A headache can be caused by tension, migraine, high blood pressure, dehydration, meningitis, or a brain tumor. Taking someone else’s headache medicine may mask symptoms while a serious condition goes untreated or worsens. Every person needs an individual medical assessment to determine the cause of their symptoms.</p>



<h3 class="wp-block-heading">2. Different Doses Are Needed for Different People</h3>



<p>Medicine doses are prescribed based on body weight, age, kidney function, liver function, and other individual factors. A dose appropriate for an adult may be dangerous for a child or elderly person. Your friend’s blood pressure medicine may be a completely different dose than what is right for your blood pressure. The wrong dose can cause toxicity (too high) or treatment failure (too low). Learn about <a href="https://www.bharatmedicalhall.com/blog/what-happens-if-you-miss-a-dose-of-medicine/">dose management in medicine</a>.</p>



<h3 class="wp-block-heading">3. Drug Interactions and Allergies</h3>



<p>The person you are giving medicine to may be taking other medicines that interact with what you are sharing. They may have an allergy to the medicine or an ingredient in it that you are unaware of. They may have a condition that makes the medicine dangerous for them – for example, giving an NSAID to someone with kidney disease. Learn about <a href="https://www.bharatmedicalhall.com/blog/can-you-mix-different-medicines-together-safely/">dangerous medicine combinations</a>.</p>



<h3 class="wp-block-heading">4. Antibiotics Require Diagnosis-Specific Selection</h3>



<p>Sharing antibiotics is especially problematic. Different bacteria cause different infections, and different antibiotics are effective against different bacteria. Giving someone your antibiotic for their “similar” infection may not work if a different bacteria is causing their infection. It can also cause antibiotic resistance. Read about <a href="https://www.bharatmedicalhall.com/blog/why-antibiotics-must-be-completed-fully/">why antibiotics must be taken correctly</a>.</p>



<h3 class="wp-block-heading">5. Controlled Substances and Addiction Risk</h3>



<p>Sharing pain medicines (tramadol, codeine) or anxiety medicines (benzodiazepines) is illegal for controlled substances and carries significant addiction risk. These medicines are controlled precisely because of their abuse potential. Sharing them without a doctor’s assessment exposes the recipient to addiction risk without the medical monitoring needed.</p>



<h3 class="wp-block-heading">6. It Is Illegal in India for Prescription Medicines</h3>



<p>Sharing prescription medicines (Schedule H and H1 medicines) in India is technically illegal. Prescription medicines require a doctor’s assessment for a reason. Providing them to someone without a prescription is an offense under the Drugs and Cosmetics Act.</p>



<h2 class="wp-block-heading">What Should You Do Instead of Sharing Medicines?</h2>



<ul class="wp-block-list"><li>For simple OTC medicines (paracetamol, antacids), buying a new pack specifically for the person needing it is affordable and safe</li><li>Encourage them to see a doctor for any symptoms requiring prescription medicines</li><li>For emergencies, suggest seeking medical attention rather than sharing prescription medicines</li><li>Know about first aid for common emergencies while waiting for medical help</li></ul>



